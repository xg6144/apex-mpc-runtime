#!/usr/bin/env python3
"""Derive the simulator's MPC parameter overrides from run_car.sh.

The simulator is only useful if it drives the *car's* controller.  Rather than
keeping a second copy of the tuning that silently drifts, this reads the
override block run_car.sh writes for the real vehicle and re-emits it with the
handful of changes the simulator interface requires:

  * topics - the gym bridge publishes /ego_racecar/odom and /scan and listens
    on /drive; there is no manual-override or IMU stream.
  * steering uses the exact same command units on both sides.  The gym bridge
    applies the car's command-to-wheel gain, asymmetric rack reach, and physical
    slew limit before the single-track dynamics see the wheel angle.
  * the safety layers that need hardware we do not simulate (VESC IMU fusion,
    the realtime grip limiter that reads it, joystick takeover).

Everything else - weights, horizon, obstacle tuning, speed caps - is whatever
run_car.sh currently says, so a change there shows up in the next sim run.

Usage:
    sim_overrides.py --raceline <csv> --map <yaml> [--speed 1.0] [--avoid true]
"""

import argparse
import os
import re
import sys


DEFAULT_RUN_CAR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    'scripts', 'run_car.sh')

# Keys whose run_car.sh value is a shell variable, or whose meaning changes in
# the simulator.  These are written by this script instead of being copied.
REPLACED = {
    'raceline_path', 'map_yaml_path', 'odom_topic', 'scan_topic',
    'drive_topic', 'manual_override_topic', 'manual_override_timeout',
    'enable_manual_override', 'speed_scale', 'enable_imu',
    'enable_realtime_grip_limit', 'enable_obstacle_avoidance',
    'enable_vesc_brake_command',
    'enable_raceline_editor', 'raceline_editor_save_path',
    'latency_compensation',
    # the sim steps (and publishes odom) far faster than the car's odometry
    'control_on_odometry', 'control_period',
    # the gym publishes the ST model's CoG pose, not a rear-axle pose
    'ego_center_offset',
}


def read_car_overrides(path):
    """Return {key: value-as-written} from run_car.sh's override heredoc."""
    with open(path) as handle:
        text = handle.read()
    block = re.search(
        r'^cat > "\$OVERRIDES" <<EOF$\n(.*?)^EOF$', text, re.M | re.S)
    if not block:
        raise SystemExit('could not find the override heredoc in ' + path)
    values = {}
    for line in block.group(1).splitlines():
        match = re.match(r'^\s{4}([a-z_][a-z0-9_]*):\s*(\S.*?)\s*$', line)
        if match:
            values[match.group(1)] = match.group(2)
    if not values:
        raise SystemExit('override heredoc in %s had no key: value lines' % path)
    return values


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--raceline', required=True)
    parser.add_argument('--map', required=True)
    parser.add_argument('--run-car', default=DEFAULT_RUN_CAR)
    parser.add_argument('--speed', default='1.0')
    parser.add_argument('--avoid', default='true')
    parser.add_argument('--editor', default='false')
    parser.add_argument('--latency', default='0.05',
                        help="run_car.sh's --latency default; the sim chain is "
                             'shorter but the controller under test is the same.')
    parser.add_argument('--set', action='append', default=[], metavar='K=V',
                        dest='overrides',
                        help='override one controller parameter for this run '
                             '(repeatable), e.g. --set contour_weight=96.0')
    parser.add_argument('-o', '--out', default='-')
    args = parser.parse_args(argv)

    car = read_car_overrides(args.run_car)
    lines = [
        '# Generated by tools/sim_overrides.py - do not edit.',
        '# Car tuning copied from %s; only the simulator interface differs.'
        % args.run_car,
        'mpc_controller:',
        '  ros__parameters:',
    ]
    carried = 0
    for key, value in car.items():
        if key in REPLACED:
            continue
        if '$' in value:            # an un-modelled shell variable slipped in
            continue
        lines.append('    %s: %s' % (key, value))
        carried += 1

    lines += [
        '',
        '    # --- simulator interface -------------------------------------',
        '    raceline_path: %s' % args.raceline,
        '    map_yaml_path: %s' % args.map,
        '    odom_topic: /ego_racecar/odom',
        '    scan_topic: /scan',
        '    drive_topic: /drive',
        '    speed_scale: %s' % args.speed,
        '    enable_obstacle_avoidance: %s' % args.avoid,
        '    enable_raceline_editor: %s' % args.editor,
        '    raceline_editor_save_path: %s'
        % (os.path.splitext(args.raceline)[0] + '_sim_edited.csv'),
        '    latency_compensation: %s' % args.latency,
        '',
        '    # No joystick, no VESC IMU: the takeover input and the grip',
        '    # limiter that reads yaw rate from it have nothing to listen to.',
        '    enable_manual_override: false',
        '    enable_imu: false',
        '    enable_realtime_grip_limit: false',
        '    enable_vesc_brake_command: false',
        '',
        '    # The bridge publishes odometry every physics step (~160 Hz), so',
        '    # control_on_odometry would clock the MPC three times faster than',
        '    # the car\'s 50 Hz particle filter ever allows.  Run it off the',
        '    # timer at the same period the car achieves instead.',
        '    control_on_odometry: false',
        '    control_period: 0.02',
        '',
        '    # On the car /pf/pose/odom is the rear axle, so the collision body',
        '    # sits ego_center_offset ahead of it.  The gym publishes the ST',
        '    # model\'s CoG as base_link and its own collision body is centred',
        '    # there (-lr + collision_body_center_x = -6 mm), so in the',
        '    # simulator that offset is already zero.',
        '    ego_center_offset: 0.0',
        '',
        '    # /drive now has the same command-unit contract as the car.',
        '    # steering_gain/min/max/rate above are copied without rescaling;',
        '    # the gym bridge converts command to physical wheel angle.',
    ]
    if args.overrides:
        pairs = []
        for item in args.overrides:
            if '=' not in item:
                raise SystemExit('--set expects key=value, got %r' % item)
            key, value = item.split('=', 1)
            pairs.append((key.strip(), value.strip()))
        # Drop any earlier line for the same key so the file has no duplicates
        # (rclpy's loader would silently keep the last, which hides typos).
        keys = {key for key, _ in pairs}
        lines = [line for line in lines
                 if line.strip().split(':')[0].strip() not in keys]
        lines += ['', '    # --- swept for this run (--set) ---']
        lines += ['    %s: %s' % pair for pair in pairs]

    text = '\n'.join(lines) + '\n'
    if args.out == '-':
        sys.stdout.write(text)
    else:
        with open(args.out, 'w') as handle:
            handle.write(text)
        print('[sim_overrides] %d car keys carried over -> %s'
              % (carried, args.out), file=sys.stderr)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
